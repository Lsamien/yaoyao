import {test,expect,type Page} from '@playwright/test'
import {mkdirSync} from 'node:fs'
const evidence='docs/verification/2026-09-10-bot-panels'
async function create(page:Page,name:string){
 await page.locator('.desktop-sidebar .sidebar-create-trigger').click()
 await page.getByRole('menuitem',{name:'新建 Bot',exact:true}).click()
 const editor=page.getByRole('dialog');await editor.getByRole('textbox',{name:'名称',exact:true}).fill(name)
 await editor.getByRole('button',{name:'保存',exact:true}).click()
 await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
}
