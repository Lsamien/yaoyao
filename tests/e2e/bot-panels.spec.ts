 await taskPicker.selectOption('__create_task__')
 await expect(page).toHaveURL(/taskId=/)
 await expect(page.getByRole('combobox',{name:'当前任务',exact:true}).locator('option')).toHaveCount(optionCount+1)
 await page.screenshot({path:evidence+'/desktop-group-task-picker.png'})
 for(let index=1;index<=12;index++){
  const created=await page.request.post('/api/app/agents',{headers:{'X-CSRF-Token':capabilities.csrfToken,Origin:'http://127.0.0.1:18832'},data:{name:`滚动验收 ${index}`,profile:'default'}})
  expect(created.ok(),await created.text()).toBe(true)
 }
 await page.reload()
 const agentList=page.locator('.desktop-sidebar .sidebar-list')
 await expect.poll(()=>agentList.evaluate(element=>element.scrollHeight-element.clientHeight)).toBeGreaterThan(0)
 await agentList.evaluate(element=>{element.scrollTop=element.scrollHeight})
 await expect.poll(()=>agentList.evaluate(element=>element.scrollTop)).toBeGreaterThan(0)
 await expect(agentList).toHaveCSS('overflow-y','auto')
 expect(await agentList.evaluate(element=>getComputedStyle(element,'::-webkit-scrollbar-thumb').backgroundColor)).not.toBe('rgba(0, 0, 0, 0)')
 await agentList.hover()
 await page.screenshot({path:evidence+'/desktop-agent-list-scroll.png'})
 await page.getByRole('button',{name:'Inspector',exact:true}).click()
 await expect(panel.locator(':scope > header')).toHaveCount(0)
 await expect(panel.getByRole('button',{name:'电脑',exact:true})).toHaveCount(0)
 await expect(panel.getByRole('button',{name:'定时任务',exact:true})).toHaveCount(0)
 await page.setViewportSize({width:375,height:812});await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'})
 await page.screenshot({path:evidence+'/phone-group-inspector.png'})
 const box=await panel.boundingBox();expect(box!.width).toBeLessThanOrEqual(375)
 await expect(panel.getByRole('button',{name:'关闭 Inspector',exact:true})).toBeVisible()
